// Generates src/generated/contracts.ts from the Foundry build in ../contracts/out:
// ABIs plus the expected runtime code hash of every contract with immutable slots masked to zero.
// Run after `forge build`: node scripts/gen-contracts.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { keccak256 } from "viem";

const OUT = new URL("../../contracts/out/", import.meta.url);
const ITEMS = [
  ["AsterismLauncher", "AsterismLauncher.sol/AsterismLauncher.json"],
  ["AsterismToken", "AsterismToken.sol/AsterismToken.json"],
  ["AsterismRenderer", "AsterismRenderer.sol/AsterismRenderer.json"],
  ["DN404Mirror", "DN404Mirror.sol/DN404Mirror.json"],
  ["LiquiditySink", "LiquiditySink.sol/LiquiditySink.json"],
];

/** Zero every immutable reference so the hash depends only on the compiled code. */
export function maskImmutables(hex, refs) {
  const bytes = Buffer.from(hex.replace(/^0x/, ""), "hex");
  for (const list of Object.values(refs ?? {})) for (const { start, length } of list) bytes.fill(0, start, start + length);
  return `0x${bytes.toString("hex")}`;
}

let src = "// Generated by scripts/gen-contracts.mjs from ../contracts/out. Do not edit.\n";
const meta = {};
for (const [name, path] of ITEMS) {
  const art = JSON.parse(readFileSync(new URL(path, OUT), "utf8"));
  const refs = art.deployedBytecode.immutableReferences ?? {};
  const masked = maskImmutables(art.deployedBytecode.object, refs);
  meta[name] = {
    codeHashMasked: keccak256(masked),
    immutableRefs: Object.values(refs).flat(),
    runtimeSize: (art.deployedBytecode.object.length - 2) / 2,
  };
  src += `export const ${name}Abi = ${JSON.stringify(art.abi)} as const;\n`;
}
src += `export const expectedCode = ${JSON.stringify(meta, null, 1)} as const;\n`;
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/generated/contracts.ts", import.meta.url), src);
writeFileSync(new URL("../src/generated/expected-code.json", import.meta.url), JSON.stringify(meta, null, 1));
const abis = Object.fromEntries(ITEMS.map(([name, path]) => [name, JSON.parse(readFileSync(new URL(path, OUT), "utf8")).abi]));
writeFileSync(new URL("../src/generated/abis.json", import.meta.url), JSON.stringify(abis));
console.log(Object.fromEntries(Object.entries(meta).map(([k, v]) => [k, v.codeHashMasked.slice(0, 18)])));
